    private void applyStyle() {
        JLabel title = new JLabel("Add a monitored directory");
        title.setFont(UiStyle.font("h2.font"));
        JLabel subtitle = UiStyle.mutedLabel("Files in this directory are hashed and checked on every scan.");
        JLabel pathCaption = new JLabel("Directory");
        pathCaption.setFont(UiStyle.font("semibold.font"));
        JLabel optionsCaption = new JLabel("Options");
        optionsCaption.setFont(UiStyle.font("semibold.font"));

        // The selected path, shown like a read-only field next to its button
        JPanel pathWell = new JPanel(new BorderLayout());
        UiStyle.styleClass(pathWell, "well");
        pathWell.setBorder(BorderFactory.createEmptyBorder(8, 12, 8, 12));
        pathLabel.setIcon(AppIcons.of(AppIcons.Glyph.FOLDER));
        pathLabel.setIconTextGap(10);
        pathLabel.setMinimumSize(new Dimension(0, 0));
        pathLabel.setPreferredSize(new Dimension(0, 20));
        pathWell.add(pathLabel, BorderLayout.CENTER);
        selectPathButton.setText("Browse...");
        JPanel pathRow = new JPanel(new BorderLayout(8, 0));
        pathRow.add(pathWell, BorderLayout.CENTER);
        pathRow.add(selectPathButton, BorderLayout.LINE_END);

        UiStyle.styleClass(createButton, UiStyle.PRIMARY);
        createButton.setIcon(AppIcons.of(AppIcons.Glyph.PLUS));
        JPanel actions = new JPanel(new FlowLayout(FlowLayout.TRAILING, 8, 0));
        actions.add(cancelButton);
        actions.add(createButton);

        JPanel form = new JPanel(new GridBagLayout());
        form.setBorder(BorderFactory.createEmptyBorder(28, 36, 28, 36));
        int row = 0;
        addRow(form, title, row++, 0);
        addRow(form, subtitle, row++, 4);
        addRow(form, Box.createHorizontalStrut(FORM_WIDTH), row++, 0);
        addRow(form, pathCaption, row++, 22);
        addRow(form, pathRow, row++, 6);
        addRow(form, optionsCaption, row++, 20);
        addRow(form, includeSubdirectoriesCheckBox, row++, 6);
        addRow(form, makeDirectoryActiveCheckBox, row++, 4);
        addRow(form, actions, row, 28);

        container = new JPanel(new GridBagLayout());
        container.add(form);
    }

    /**
     * Adds a component as the next full-width row of the form.
     *
     * @param form      the form panel
     * @param component the component to add
     * @param row       the row index
     * @param gapAbove  the space above the component, in pixels
     */
    private static void addRow(JPanel form, Component component, int row, int gapAbove) {
        GridBagConstraints constraints = new GridBagConstraints();
        constraints.gridx = 0;
        constraints.gridy = row;
        constraints.weightx = 1;
        constraints.fill = GridBagConstraints.HORIZONTAL;
        constraints.insets = new Insets(gapAbove, 0, 0, 0);
        form.add(component, constraints);
    }

